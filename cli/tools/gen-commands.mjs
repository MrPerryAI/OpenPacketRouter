#!/usr/bin/env node
// Writes examples/<lab>/commands.txt for every lab: each device's configuration as CLI commands (what
// `show running-config` prints), next to spec.json. Replaying a device's section on a blank device of the
// same kind rebuilds it. `--check` exits 1 if a file is out of date.
import fs from "node:fs";
import path from "node:path";
import {fileURLToPath} from "node:url";
import {createSession} from "../src/index.js";
import {engineBackend} from "../src/backends/engine.js";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const EX = path.join(ROOT, "examples");
const check = process.argv.includes("--check");
let stale = 0;
for (const lab of fs.readdirSync(EX, {withFileTypes: true}).filter(e => e.isDirectory()).map(e => e.name)) {
  const specFile = path.join(EX, lab, "spec.json");
  if (!fs.existsSync(specFile)) continue;
  const spec = JSON.parse(fs.readFileSync(specFile, "utf8"));
  const backend = engineBackend(spec);
  const out = [
    `! ${spec.name || lab}: the configuration of every device in spec.json, as CLI commands.`,
    "! Open a console with: node cli/bin/opr-cli.mjs examples/" + lab + "/spec.json DEVICE",
    "! Generated by cli/tools/gen-commands.mjs: do not edit by hand.",
  ];
  for (const device of backend.devices()) {
    const s = createSession(backend, device);
    s.exec("enable");
    out.push("", `! ===== ${device} (${backend.kind(device)}) =====`, s.exec("show running-config").output);
  }
  const text = out.join("\n") + "\n", file = path.join(EX, lab, "commands.txt");
  if (check) { if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== text) { console.error(`${path.relative(ROOT, file)} is out of date`); stale++; } }
  else fs.writeFileSync(file, text);
}
if (stale) { console.error("run node cli/tools/gen-commands.mjs"); process.exit(1); }
